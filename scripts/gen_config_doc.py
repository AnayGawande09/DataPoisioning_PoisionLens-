r"""Regenerate docs/CONFIG.md from ScanConfig field defaults and descriptions.

.venv\Scripts\python scripts\gen_config_doc.py
"""

from __future__ import annotations

import sys
from pathlib import Path

from pydantic import BaseModel

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from poisonlens.core.config import ScanConfig  # noqa: E402

HEADER = """# Scan configuration reference

Generated by `scripts/gen_config_doc.py` from `poisonlens/core/config.py` — do not edit by hand
(`tests/unit/test_config_doc.py` fails if this file is stale).

Defaults below are the **Standard** profile. `configs/scan_quick.yaml` and `configs/scan_deep.yaml`
override the `probe.*` values listed in spec section 4.2. Unknown keys in any YAML or override are errors.

- **spec** — value fixed by `POISONLENS_V2_SPEC.md` or the build plan.
- **provisional** — the spec leaves it open. A starting point only: it must be validated by the
  Phase 12 benchmark, and is never tuned on test fixtures.

| Key | Default | Source | Notes |
| :--- | :--- | :--- | :--- |
"""


def _rows(model: BaseModel, prefix: str = "") -> list[str]:
    out: list[str] = []
    for name, field in type(model).model_fields.items():
        value = getattr(model, name)
        if isinstance(value, BaseModel):
            out.extend(_rows(value, f"{prefix}{name}."))
            continue
        desc = field.description or ""
        source, _, note = desc.partition(":")
        if source.startswith("spec"):
            source_label = "spec"
        elif source.startswith("provisional"):
            source_label = "provisional"
        else:
            source_label, note = "-", desc
        note = note.strip()
        if source.startswith("spec ("):
            note = f"{source[5:-1]}: {note}"  # e.g. "build plan: ..."
        cell = repr(value).replace("|", "\\|")
        note = note.replace("|", "\\|")
        out.append(f"| `{prefix}{name}` | `{cell}` | {source_label} | {note} |")
    return out


def render() -> str:
    return HEADER + "\n".join(_rows(ScanConfig())) + "\n"


if __name__ == "__main__":
    (ROOT / "docs" / "CONFIG.md").write_text(render(), encoding="utf-8", newline="\n")
    print("wrote docs/CONFIG.md")
